#!/bin/bash
# One-time setup for building the hotdogb XNU kernel in WSL (no Mac needed after).
#
#   tools/wsl-xnu-setup.sh            build the toolchain and unpack the seed files
#   tools/wsl-xnu-setup.sh --tools    only rebuild the toolchain (keeps the tree)
#
# Everything lands in $XNU_LINUX (default ~/xnu-linux, on the Linux filesystem:
# XNU does not build on /mnt/c):
#   toolchain/   xcrun, clang wrappers, ld64 & cctools (Theos), mig, unifdef,
#                host-cc, iig/plutil/install stand-ins
#   build/clang  clang $LLVM_VERSION with Apple's XNU builtins added
#                (tools/wsl-xnu/clang-xnu-builtins.py; ~40 min the first time)
#   sdk/         MacOSX.sdk from the Mac
#   dxb/         xnu tree, fakeroot (libfirehose_kernel.a), applied-patches, build/
#
# Seed files (made once on the Mac, see below) are read from work/wsl-seed/:
#   mac-sdk.tgz        MacOSX.sdk                 dxb-fakeroot.tgz  work/dxb/fakeroot
#   dxb-xnu.tgz        work/dxb/xnu + applied-patches
#   dxb-obj.tgz        work/dxb/build without objects (for the iig outputs)
# Mac (once), then fetch from the NAS with Git Bash into work/wsl-seed:
#   cd ~/gitrepos/ios-hotdogb && SDK=$(cd "$(xcrun -sdk macosx --show-sdk-path)" && pwd -P) &&
#   tar czf /tmp/mac-sdk.tgz -C "$(dirname "$SDK")" "$(basename "$SDK")" &&
#   tar czf /tmp/dxb-fakeroot.tgz -C work/dxb fakeroot &&
#   tar czf /tmp/dxb-obj.tgz --exclude='*.o' --exclude='*.dSYM' --exclude='kernel.development*' -C work/dxb build &&
#   tar czf /tmp/dxb-xnu.tgz -C work/dxb xnu applied-patches &&
#   scp /tmp/mac-sdk.tgz /tmp/dxb-fakeroot.tgz /tmp/dxb-obj.tgz /tmp/dxb-xnu.tgz peketr@truenas.local:ios-kernels/
#
# Needs (apt): clang-21 lld-21 llvm-21 llvm-21-dev cmake ninja-build gcc csh bison flex
# m4 uuid-dev python3 git, and
# Theos' Linux iOS toolchain in ~/theos (ld64-609 + cctools; override: THEOS_BIN).
#
# iig: Apple's IOKit Interface Generator is Xcode-only. Its DriverKit outputs come
# from dxb-obj.tgz, keyed by the sha256 of each .iig; the build stops if a patch
# changes an .iig. Then remake dxb-obj.tgz on the Mac after a Mac build and rerun
# this script with --tools.
set -euo pipefail
ROOT=$(cd "$(dirname "$0")/.." && pwd)
L=${XNU_LINUX:-$HOME/xnu-linux}
SEED=${WSL_SEED:-$ROOT/work/wsl-seed}
LLVM=${LLVM:-/usr/lib/llvm-21}
THEOS_BIN=${THEOS_BIN:-$HOME/theos/toolchain/linux/iphone/bin}
BOOTSTRAP_CMDS_TAG=bootstrap_cmds-129   # Xcode 27.2 mig: "stub generated by bootstrap_cmds-129"
UNIFDEF_REV=08d12cd3059fe072929ea001ad9833f5487fd355
SRC=$ROOT/tools/wsl-xnu

tools_only=0
case ${1:-} in
--tools) tools_only=1 ;;
'') ;;
-h|--help) sed -n '2,39p' "$0"; exit 0 ;;
*) echo "unknown argument: $1" >&2; exit 2 ;;
esac

case $L in /mnt/*) echo "XNU_LINUX must be on the Linux filesystem, not $L" >&2; exit 1 ;; esac

need() { command -v "$1" >/dev/null || { echo "missing: $1 ($2)" >&2; exit 1; }; }
need cmake cmake; need ninja ninja-build; need gcc gcc; need csh "csh: xnu SETUP/config/doconf"; need bison bison; need flex flex; need m4 m4; need python3 python3; need git git
[ -x "$LLVM/bin/clang" ] || { echo "missing: $LLVM/bin/clang (apt install clang-21)" >&2; exit 1; }
[ -x "$LLVM/bin/dsymutil" ] || { echo "missing: $LLVM/bin/dsymutil (apt install llvm-21)" >&2; exit 1; }
[ -f "$LLVM/lib/cmake/llvm/LLVMConfig.cmake" ] || { echo "missing: LLVM cmake files (apt install llvm-21-dev)" >&2; exit 1; }
LLVM_VERSION=$("$LLVM/bin/llvm-config" --version)
[ -x "$THEOS_BIN/ld" ] || { echo "missing: $THEOS_BIN/ld (Theos Linux toolchain)" >&2; exit 1; }
[ -f /usr/include/uuid/uuid.h ] || { echo "missing: uuid/uuid.h (apt install uuid-dev)" >&2; exit 1; }

mkdir -p "$L"/{src,build,sdk,dxb}
unpack() { # tarball destdir
	[ -f "$SEED/$1" ] || { echo "missing seed file $SEED/$1 (see --help)" >&2; exit 1; }
	echo "unpacking $1"
	tar xzf "$SEED/$1" -C "$2" --warning=no-unknown-keyword
}

# --- seeds: SDK, fakeroot, xnu tree ---------------------------------------------
if [ $tools_only = 0 ]; then
	[ -d "$L/sdk/MacOSX.sdk" ] || unpack mac-sdk.tgz "$L/sdk"
	mkdir -p "$L/sdk/MacOSX.platform"
	[ -d "$L/dxb/fakeroot" ] || unpack dxb-fakeroot.tgz "$L/dxb"
	if [ -d "$L/dxb/xnu" ]; then
		echo "$L/dxb/xnu exists; leaving the tree alone"
	else
		unpack dxb-xnu.tgz "$L/dxb"
	fi
fi
XNU=$L/dxb/xnu
[ -d "$XNU/osfmk/mach" ] || { echo "no xnu tree at $XNU" >&2; exit 1; }

# --- clang with the XNU kalloc_type builtins -----------------------------------
# Xcode's clang has __builtin_xnu_type_signature/_summary/_types_compatible;
# upstream (and swiftlang) clang do not. Built standalone against $LLVM's
# libraries, so the source must be exactly that LLVM version.
CL=$L/build/clang
stamp="$LLVM_VERSION $(sha256sum < "$SRC/clang-xnu-builtins.py" | cut -c1-16)"
if [ "$(cat "$CL/.xnu-stamp" 2>/dev/null)" != "$stamp" ] || [ ! -x "$CL/bin/clang" ]; then
	P=$L/src/llvm-project
	if [ ! -d "$P" ] || [ "$(git -C "$P" describe --tags 2>/dev/null)" != "llvmorg-$LLVM_VERSION" ]; then
		rm -rf "$P"
		git clone -q --depth 1 --branch "llvmorg-$LLVM_VERSION" --filter=blob:none --sparse 			https://github.com/llvm/llvm-project.git "$P"
		git -C "$P" sparse-checkout set clang cmake llvm/cmake llvm/utils/lit third-party \
			compiler-rt/lib/profile compiler-rt/include/profile
	fi
	git -C "$P" checkout -q -- clang
	python3 "$SRC/clang-xnu-builtins.py" "$P"
	echo "building clang $LLVM_VERSION with the XNU builtins (log: $CL/ninja.log) ..."
	mkdir -p "$CL"
	cmake -G Ninja -S "$P/clang" -B "$CL" -DLLVM_DIR="$LLVM/lib/cmake/llvm" -DCMAKE_BUILD_TYPE=Release 		-DCMAKE_C_COMPILER="$LLVM/bin/clang" -DCMAKE_CXX_COMPILER="$LLVM/bin/clang++" -DLLVM_USE_LINKER=lld 		-DCLANG_INCLUDE_TESTS=OFF -DCLANG_INCLUDE_DOCS=OFF -DLLVM_INCLUDE_TESTS=OFF -DCLANG_ENABLE_ARCMT=OFF 		-DCLANG_ENABLE_STATIC_ANALYZER=OFF -DCLANG_PLUGIN_SUPPORT=OFF -DCLANG_BUILD_EXAMPLES=OFF 		-DLLVM_ENABLE_ASSERTIONS=OFF > "$CL/cmake.log" 2>&1 || { tail -30 "$CL/cmake.log" >&2; exit 1; }
	ninja -C "$CL" -j"$(nproc)" clang > "$CL/ninja.log" 2>&1 || { grep -a -A5 'error:' "$CL/ninja.log" | head -40 >&2; exit 1; }
	echo "$stamp" > "$CL/.xnu-stamp"
fi

# --- toolchain ---------------------------------------------------------------
TC=$L/toolchain
rm -rf "$TC"; mkdir -p "$TC"/{bin,libexec,lib,share/iig}
cp -r "$SRC/host-inc" "$TC/host-inc"
for t in xcrun host-cc iig plutil install; do cp "$SRC/$t" "$TC/bin/$t"; chmod +x "$TC/bin/$t"; done
for c in clang clang++; do
	sed -e "s|@CLANG@|$CL/bin/$c|; s|@TC@|$TC|g" "$SRC/clang.in" > "$TC/bin/$c"
	chmod +x "$TC/bin/$c"
done
for t in ld strip nm otool lipo libtool nmedit codesign_allocate ctf_insert; do
	ln -sf "$THEOS_BIN/$t" "$TC/bin/$t"
done
ln -sf clang "$TC/bin/cc"   # mig.sh preprocesses with $(dirname mig)/cc
ln -sf "$LLVM/bin/llvm-ar" "$TC/bin/ar"
ln -sf "$LLVM/bin/llvm-ranlib" "$TC/bin/ranlib"
ln -sf "$LLVM/bin/dsymutil" "$TC/bin/dsymutil"
ln -sf "$(command -v python3)" "$TC/bin/python"   # lldbmacros install: #!/usr/bin/env python
gcc -std=gnu11 -O1 -I"$TC/host-inc" -c "$SRC/darwin-compat.c" -o "$TC/lib/darwin-compat.o"

# libclang_rt.cc_kext.a (xnu links -lcc_kext): Xcode's libclang_rt.cc_kext.a is compiler-rt's
# builtins plus its profile runtime, built -mkernel -DKERNEL_USE
# (compiler-rt/cmake/Modules/CompilerRTDarwinUtils.cmake). The kernel only takes the
# profile part (OSKext's PGO support), so that is all this builds.
P=$L/src/llvm-project
[ -d "$P/compiler-rt/lib/profile" ] ||
	git -C "$P" sparse-checkout add compiler-rt/lib/profile compiler-rt/include/profile
# The driver turns -lcc_kext into <resource dir>/lib/darwin/libclang_rt.cc_kext.a, as
# in Xcode (and drops it silently when that file is missing).
RT=$("$CL/bin/clang" -print-resource-dir)/lib/darwin
K=$L/build/cc_kext; rm -rf "$K"; mkdir -p "$K" "$RT"
for f in InstrProfiling InstrProfilingBuffer InstrProfilingPlatformDarwin InstrProfilingWriter \
		InstrProfilingInternal InstrProfilingVersionVar; do
	"$TC/bin/clang" -arch arm64 -isysroot "$L/sdk/MacOSX.sdk" -mmacosx-version-min=11.0 -mkernel \
		-fPIC -O3 -fvisibility=hidden -DVISIBILITY_HIDDEN -fomit-frame-pointer -DKERNEL_USE -w \
		-I"$P/compiler-rt/include" -c "$P/compiler-rt/lib/profile/$f.c" -o "$K/$f.o"
done
rm -f "$RT/libclang_rt.cc_kext.a"
"$LLVM/bin/llvm-ar" --format=darwin rcs "$RT/libclang_rt.cc_kext.a" "$K"/*.o

# unifdef
if [ ! -d "$L/src/unifdef" ]; then
	git clone -q https://github.com/fanf2/unifdef.git "$L/src/unifdef"
fi
git -C "$L/src/unifdef" checkout -q "$UNIFDEF_REV"
(cd "$L/src/unifdef" && echo '"unifdef-2.12 (git)"' > version.h && gcc -std=gnu11 -O2 -o "$TC/bin/unifdef" unifdef.c)

# mig: migcom from bootstrap_cmds, built against xnu's own <mach/*.h>
if [ ! -d "$L/src/bootstrap_cmds" ]; then
	git clone -q https://github.com/apple-oss-distributions/bootstrap_cmds.git "$L/src/bootstrap_cmds"
fi
git -C "$L/src/bootstrap_cmds" fetch -q --tags 2>/dev/null || true
git -C "$L/src/bootstrap_cmds" checkout -q "$BOOTSTRAP_CMDS_TAG"
M=$L/build/migcom; rm -rf "$M"; mkdir -p "$M/inc/sys/_types"
cp "$L/src/bootstrap_cmds/migcom.tproj"/* "$M/"
rm -f "$M/handler.c"   # not part of the Xcode target
cp -r "$XNU/osfmk/mach" "$M/inc/mach"
cp "$XNU/bsd/sys/appleapiopts.h" "$M/inc/sys/"
cp "$XNU/bsd/sys/_types/_mach_port_t.h" "$XNU/bsd/sys/_types/_uuid_t.h" "$M/inc/sys/_types/"
cp -r "$SRC/mig-inc/." "$M/inc/"
(
	cd "$M"
	bison -y -d parser.y -o y.tab.c 2>/dev/null
	flex -o lex.yy.c lexxer.l
	gcc -std=gnu11 -O2 -w -I. -Iinc -include inc/mig_shim.h \
		-DMIG_VERSION="\"$BOOTSTRAP_CMDS_TAG\"" -o "$TC/libexec/migcom" *.c
)
cp "$L/src/bootstrap_cmds/migcom.tproj/mig.sh" "$TC/bin/mig"; chmod +x "$TC/bin/mig"

# iig outputs from the Mac build tree
if [ -f "$SEED/dxb-obj.tgz" ]; then
	tmp=$(mktemp -d)
	tar xzf "$SEED/dxb-obj.tgz" -C "$tmp" --warning=no-unknown-keyword --wildcards \
		'build/xnu.obj/*/iokit/DriverKit/*.h' 'build/xnu.obj/*/iokit/DriverKit/*.iig.cpp'
	G=$(dirname "$(ls "$tmp"/build/xnu.obj/*/iokit/DriverKit/IOService.h | head -1)")
	for f in "$XNU"/iokit/DriverKit/*.iig; do
		b=$(basename "$f" .iig)
		cp "$G/$b.h" "$G/$b.iig.cpp" "$TC/share/iig/"
		sha256sum < "$f" | cut -d' ' -f1 > "$TC/share/iig/$b.iig.sha256"
	done
	rm -rf "$tmp"
else
	echo "missing $SEED/dxb-obj.tgz: no iig outputs" >&2; exit 1
fi

echo
echo "toolchain ready in $TC"
"$TC/bin/xcrun" -sdk macosx -show-sdk-path && echo "SDK $("$TC/bin/xcrun" -sdk macosx -show-sdk-version)"
echo "next: tools/wsl-build.sh"
